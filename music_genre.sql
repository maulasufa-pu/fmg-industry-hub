-- Music Genre Database
-- Table structure for music genres and sub-genres
-- Based on comprehensive list of music types

CREATE TABLE IF NOT EXISTS music_genres (
    id SERIAL PRIMARY KEY,
    genre VARCHAR(100) NOT NULL,
    sub_genre VARCHAR(150) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Create index for faster queries
CREATE INDEX idx_genre ON music_genres(genre);
CREATE INDEX idx_sub_genre ON music_genres(sub_genre);


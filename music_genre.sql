-- Create a view for easier genre browsing
CREATE OR REPLACE VIEW genre_summary AS
SELECT 
    genre,
    COUNT(*) as sub_genre_count,
    STRING_AGG(sub_genre, ', ' ORDER BY sub_genre) as sub_genres
FROM music_genres
GROUP BY genre
ORDER BY genre;

-- Query examples:
-- Get all genres: SELECT DISTINCT genre FROM music_genres ORDER BY genre;
-- Get sub-genres for a specific genre: SELECT sub_genre FROM music_genres WHERE genre = 'Rock' ORDER BY sub_genre;
-- Search sub-genres: SELECT * FROM music_genres WHERE sub_genre ILIKE '%jazz%';
-- Get genre summary: SELECT * FROM genre_summary;

COMMENT ON TABLE music_genres IS 'Comprehensive database of music genres and sub-genres';
COMMENT ON COLUMN music_genres.genre IS 'Main genre category';
COMMENT ON COLUMN music_genres.sub_genre IS 'Specific sub-genre or style within the main genre';
